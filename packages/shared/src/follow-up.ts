// Send targets. Each reuses toLinkUrl's phone/email parsing (links.ts) rather than re-validating -
// a contact's phone/email are free text (packages/shared/src/schemas.ts contactFields), not
// pre-normalised the way a profile's own contact fields are (profile-contact.ts).
// ---------------------------------------------------------------------------

const FOLLOW_UP_EMAIL_SUBJECT = 'Great to meet you';

/** Whether `contact` has data this channel's button needs (issue #33: only shown channels a contact
 * has data for). 'copy' always has something to copy. */
export function followUpChannelAvailable(
  channel: FollowUpChannel,
  contact: {
    phone: string | null;
    email: string | null;
    telegram: string | null;
    linkedinUrl: string | null;
    xHandle: string | null;
  },
): boolean {
  switch (channel) {
    case 'whatsapp':
    case 'sms':
      return toLinkUrl('phone', contact.phone) !== null;
    case 'email':
      return toLinkUrl('email', contact.email) !== null;
    case 'telegram':
      return toLinkUrl('telegram', contact.telegram) !== null;
    case 'linkedin':
      return toLinkUrl('linkedin', contact.linkedinUrl) !== null;
    case 'x':
      return toLinkUrl('x', contact.xHandle) !== null;
    case 'copy':
      return true;
  }
}

/** `https://wa.me/<digits>?text=<encoded>`, or null when `phone` isn't a usable number. */
export function followUpWhatsAppUrl(phone: string | null | undefined, message: string): string | null {
  const tel = toLinkUrl('phone', phone);
  if (!tel) return null;
  return `https://wa.me/${tel.replace(/^tel:\+?/, '')}?text=${encodeURIComponent(message)}`;
}

/**
 * `sms:<phone>?&body=<encoded>` for a mobile browser (native uses expo-sms's sendSMSAsync instead,
 * which needs no URL). The `?&` separator - neither a bare `?` nor `&` - is the one both iOS and
 * Android's SMS apps accept.
 */
export function followUpSmsWebUrl(phone: string | null | undefined, message: string): string | null {
  const tel = toLinkUrl('phone', phone);
  if (!tel) return null;
  return `sms:${tel.replace(/^tel:/, '')}?&body=${encodeURIComponent(message)}`;
}

/** `mailto:<email>?subject=Great to meet you&body=<encoded>`, or null when `email` isn't usable. */
export function followUpMailtoUrl(email: string | null | undefined, message: string): string | null {
  const mailto = toLinkUrl('email', email);
  if (!mailto) return null;
  return `${mailto}?subject=${encodeURIComponent(FOLLOW_UP_EMAIL_SUBJECT)}&body=${encodeURIComponent(message)}`;
}
